"""Generate bounded checkpoint adapters from liblcf 0.8.1's field declarations (MIT)."""
from pathlib import Path
import re
import sys

source = Path(sys.argv[1]) / 'src' / 'generated'
fields = {}
pattern = r'static TypedField<rpg::(\w+), ([^\n]+)> \w+\(\s*&rpg::\w+::(\w+),'
for file in sorted(source.glob('*.cpp')):
    for cls, kind, member in re.findall(pattern, file.read_text(encoding='utf-8')):
        fields.setdefault(cls, {})[member] = kind

pending, selected, missing = ['Save'], set(), set()
headers = source / 'lcf' / 'rpg'
parents = {}
def canonical(cls):
    if '::' in cls:
        owner, nested = cls.split('::', 1)
        text = (headers / (owner.lower() + '.h')).read_text(encoding='utf-8')
        if not re.search(r'(?:struct|class)\s+' + re.escape(nested) + r'\s*\{', text):
            parent = re.search(r'class ' + re.escape(owner) + r'\s*:\s*public\s+(\w+)', text)
            if parent:
                return canonical(parent[1] + '::' + nested)
    return cls
while pending:
    cls = canonical(pending.pop())
    if cls in selected:
        continue
    selected.add(cls)
    header = (headers / (cls.split('::')[0].lower() + '.h')).read_text(encoding='utf-8')
    parent = re.search(r'class ' + re.escape(cls) + r'\s*:\s*public\s+(\w+)', header)
    if parent:
        parents[cls] = parent[1]
        pending.append(parent[1])
    for kind in fields.get(cls, {}).values():
        for child in re.findall(r'rpg::(\w+(?:::\w+)*)', kind):
            if (headers / (child.split('::')[0].lower() + '.h')).exists():
                pending.append(child)
            else:
                missing.add(child)

if len(sys.argv) < 3:
    print('Types:', ', '.join(sorted(selected)))
    print('Raw adapters:', ', '.join(sorted(missing)))
    print('Fields:', sum(len(fields.get(cls, {})) for cls in selected))
    raise SystemExit(0)

raw = {
    'Equipment': ['weapon_id', 'shield_id', 'armor_id', 'helmet_id', 'accessory_id'],
    'MoveCommand': ['command_id', 'parameter_a', 'parameter_b', 'parameter_c', 'parameter_string'],
    'EventCommand': ['code', 'indent', 'string', 'parameters'],
    'Rect': ['l', 't', 'r', 'b'],
}
unknown = missing - raw.keys()
if unknown:
    raise RuntimeError('Missing raw adapters: ' + ', '.join(sorted(unknown)))
for cls in missing:
    fields[cls] = dict.fromkeys(raw[cls], '')
selected |= missing
for cls in sorted(selected):
    header = (headers / (cls.split('::')[0].lower() + '.h')).read_text(encoding='utf-8')
    equality = re.search(r'inline bool operator==\(const ' + re.escape(cls) + r'& l, const ' + re.escape(cls) + r'& r\)\s*\{(.*?)\n\s*\}', header, re.S)
    if not equality:
        raise RuntimeError('Missing equality declaration: ' + cls)
    members = list(dict.fromkeys(re.findall(r'l\.(\w+)', equality[1])))
    # liblcf equality ignores record IDs, but map restore needs their original keys.
    if '::' not in cls and re.search(r'\bint ID = 0;', header):
        members.insert(0, 'ID')
    fields[cls] = dict.fromkeys(members, '')

def members_for(cls):
    return (members_for(parents[cls]) if cls in parents else []) + list(fields[cls])

lines = [
    '// Generated by rocketrpg/generate_checkpoint_json.py from liblcf 0.8.1 (MIT).',
    '// liblcf copyright and permission notice: rocketrpg/liblcf-LICENSE.txt.',
    '// Part of the GPL-3.0-or-later RocketRPG Player modification.',
    '#pragma once',
    '#include <nlohmann/json.hpp>',
    '#include <lcf/rpg/save.h>',
    '#include <lcf/dbbitarray.h>',
    'namespace lcf {',
    'inline void to_json(nlohmann::json& j, const DBString& value) { j = std::string(value); }',
    'inline void from_json(const nlohmann::json& j, DBString& value) { value = DBString(j.get<std::string>()); }',
    'template<class T> void to_json(nlohmann::json& j, const DBArray<T>& value) { j = std::vector<T>(value.begin(), value.end()); }',
    'template<class T> void from_json(const nlohmann::json& j, DBArray<T>& value) { auto v = j.get<std::vector<T>>(); value = DBArray<T>(v.begin(), v.end()); }',
    'inline void to_json(nlohmann::json& j, const DBBitArray& value) { j = nlohmann::json::array(); for (bool v : value) j.push_back(v); }',
    'inline void from_json(const nlohmann::json& j, DBBitArray& value) { auto v = j.get<std::vector<bool>>(); value = DBBitArray(v.begin(), v.end()); }',
    'namespace rpg {',
]
for cls in sorted(selected):
    lines += [f'void to_json(nlohmann::json&, const {cls}&);', f'void from_json(const nlohmann::json&, {cls}&);']
for cls in sorted(selected):
    members = members_for(cls)
    lines += [f'inline void to_json(nlohmann::json& j, const {cls}& value) {{', '  j = nlohmann::json::object();']
    lines += [f'  j["{member}"] = value.{member};' for member in members]
    lines += ['}', f'inline void from_json(const nlohmann::json& j, {cls}& value) {{',
              f'  if (!j.is_object() || j.size() != {len(members)}) throw std::runtime_error("Invalid {cls} checkpoint");']
    lines += [f'  j.at("{member}").get_to(value.{member});' for member in members]
    lines += ['}']
lines += ['} // namespace rpg', '} // namespace lcf', '']
Path(sys.argv[2]).write_text('\n'.join(lines), encoding='utf-8')
